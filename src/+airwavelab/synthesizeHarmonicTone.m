function signal = synthesizeHarmonicTone(fundamentalFrequency, ...
        harmonicAmplitudes, harmonicPhases, sampleRate, durationSeconds)
%SYNTHESIZEHARMONICTONE Add sinusoidal harmonics into a periodic tone.

    validateattributes(fundamentalFrequency, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    validateattributes(harmonicAmplitudes, {'numeric'}, ...
        {'vector', 'real', 'finite', 'nonempty'});
    validateattributes(harmonicPhases, {'numeric'}, ...
        {'vector', 'real', 'finite', 'numel', numel(harmonicAmplitudes)});
    validateattributes(sampleRate, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    validateattributes(durationSeconds, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    harmonicAmplitudes = harmonicAmplitudes(:);
    harmonicPhases = harmonicPhases(:);
    assert(numel(harmonicAmplitudes)*fundamentalFrequency < sampleRate/2, ...
        "AirWaveLab:HarmonicAboveNyquist", ...
        "Every synthesized harmonic must be below the Nyquist frequency.");

    sampleCount = max(1, round(sampleRate*durationSeconds));
    time = reshape(0:sampleCount-1, [], 1) / sampleRate;
    samples = zeros(sampleCount, 1);
    for harmonic = 1:numel(harmonicAmplitudes)
        samples = samples + harmonicAmplitudes(harmonic) * ...
            sin(2*pi*harmonic*fundamentalFrequency*time + ...
            harmonicPhases(harmonic));
    end
    signal = airwavelab.createSignal(samples, sampleRate, ...
        string(fundamentalFrequency) + " Hz, " + ...
        string(numel(harmonicAmplitudes)) + " harmonics");
end
