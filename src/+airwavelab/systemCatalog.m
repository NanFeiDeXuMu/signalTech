function systems = systemCatalog()
%SYSTEMCATALOG Example systems with theoretical classifications.

    systems(1) = entry("Gain", @(x) 2*x, true, true, true, true);
    systems(2) = entry("Square", @(x) x.^2, false, true, true, true);
    systems(3) = entry("Time-varying gain", ...
        @(x) reshape(0:numel(x)-1, [], 1).*x, true, false, true, false);
    systems(4) = entry("Two-tap FIR", ...
        @(x) filter([1, 0.5], 1, x), true, true, true, true);
    systems(5) = entry("One-sample advance", ...
        @(x) [x(2:end); 0], true, true, false, true);
    systems(6) = entry("Accumulator", @cumsum, true, true, true, false);
end

function value = entry(name, apply, linear, timeInvariant, causal, stable)
    value = struct( ...
        "name", name, ...
        "apply", apply, ...
        "linear", linear, ...
        "timeInvariant", timeInvariant, ...
        "causal", causal, ...
        "stable", stable);
end
