function analysis = analyzeHarmonics(signal, fundamentalFrequency, harmonicCount)
%ANALYZEHARMONICS Project a finite signal onto a Fourier harmonic basis.

    airwavelab.validateSignal(signal);
    validateattributes(fundamentalFrequency, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    validateattributes(harmonicCount, {'numeric'}, ...
        {'scalar', 'integer', 'positive', 'finite'});
    assert(harmonicCount*fundamentalFrequency < signal.sampleRate/2, ...
        "AirWaveLab:HarmonicAboveNyquist", ...
        "Every analyzed harmonic must be below the Nyquist frequency.");

    samples = signal.samples;
    sampleCount = numel(samples);
    time = reshape(0:sampleCount-1, [], 1) / signal.sampleRate;
    dc = mean(samples);
    cosineCoefficient = zeros(harmonicCount, 1);
    sineCoefficient = zeros(harmonicCount, 1);
    reconstruction = dc * ones(sampleCount, 1);

    for harmonic = 1:harmonicCount
        cosineBasis = cos(2*pi*harmonic*fundamentalFrequency*time);
        sineBasis = sin(2*pi*harmonic*fundamentalFrequency*time);
        cosineCoefficient(harmonic) = ...
            2/sampleCount * sum(samples .* cosineBasis);
        sineCoefficient(harmonic) = ...
            2/sampleCount * sum(samples .* sineBasis);
        reconstruction = reconstruction + ...
            cosineCoefficient(harmonic)*cosineBasis + ...
            sineCoefficient(harmonic)*sineBasis;
    end

    errorSamples = samples - reconstruction;
    signalPower = mean(samples.^2);
    errorPower = mean(errorSamples.^2);
    if errorPower == 0
        reconstructionSnrDb = Inf;
    elseif signalPower == 0
        reconstructionSnrDb = -Inf;
    else
        reconstructionSnrDb = 10*log10(signalPower/errorPower);
    end

    harmonicNumber = reshape(1:harmonicCount, [], 1);
    analysis = struct( ...
        "fundamentalFrequencyHz", double(fundamentalFrequency), ...
        "harmonicNumber", harmonicNumber, ...
        "frequencyHz", harmonicNumber*fundamentalFrequency, ...
        "dcCoefficient", dc, ...
        "cosineCoefficient", cosineCoefficient, ...
        "sineCoefficient", sineCoefficient, ...
        "amplitude", hypot(cosineCoefficient, sineCoefficient), ...
        "phaseRadians", atan2(cosineCoefficient, sineCoefficient), ...
        "reconstruction", airwavelab.createSignal(reconstruction, ...
            signal.sampleRate, signal.name + " | harmonic reconstruction"), ...
        "mse", errorPower, ...
        "reconstructionSnrDb", reconstructionSnrDb, ...
        "capturedPowerRatio", mean(reconstruction.^2) / max(signalPower, eps));
end
