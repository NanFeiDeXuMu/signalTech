function metrics = measureSignal(signal)
%MEASURESIGNAL Measure basic finite-record signal properties.

    airwavelab.validateSignal(signal);
    squared = abs(signal.samples).^2;
    metrics = struct( ...
        "name", signal.name, ...
        "sampleCount", numel(signal.samples), ...
        "durationSeconds", numel(signal.samples)/signal.sampleRate, ...
        "peak", max(abs(signal.samples)), ...
        "rms", sqrt(mean(squared)), ...
        "energy", sum(squared), ...
        "averagePower", mean(squared));
end

