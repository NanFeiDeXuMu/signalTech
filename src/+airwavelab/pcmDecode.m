function signal = pcmDecode(packet)
%PCMDECODE Reconstruct a canonical signal from an AirWaveLab PCM packet.

    required = {'format', 'bitDepth', 'sampleRate', 'sampleCount', ...
        'bitstream', 'sourceName'};
    assert(isstruct(packet) && isscalar(packet) && ...
        all(isfield(packet, required)), "AirWaveLab:InvalidPCM", ...
        "PCM packet is missing required fields.");
    validateattributes(packet.bitDepth, {'numeric'}, ...
        {'scalar', 'integer', '>=', 2, '<=', 24, 'finite'});
    validateattributes(packet.sampleRate, {'numeric'}, ...
        {'scalar', 'real', 'positive', 'finite'});
    validateattributes(packet.sampleCount, {'numeric'}, ...
        {'scalar', 'integer', 'positive', 'finite'});
    validateattributes(packet.bitstream, {'logical'}, {'column'});
    expectedBits = packet.sampleCount*packet.bitDepth;
    assert(numel(packet.bitstream) == expectedBits, ...
        "AirWaveLab:InvalidPCM", ...
        "PCM bitstream length does not match its metadata.");

    bitRows = reshape(packet.bitstream, packet.bitDepth, ...
        packet.sampleCount).';
    weights = 2.^reshape(packet.bitDepth-1:-1:0, [], 1);
    unsignedCodes = double(bitRows)*weights;
    scale = 2^(packet.bitDepth-1);
    samples = (unsignedCodes-scale)/scale;
    signal = airwavelab.createSignal(samples, packet.sampleRate, ...
        packet.sourceName + " | PCM " + string(packet.bitDepth) + "-bit");
end
